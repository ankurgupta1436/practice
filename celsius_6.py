#Program to convert Celsius to Fahrenheit and Kilometer to Meter
# Celsius to Fahrenheit
c = float(input('Enter temperature in Celsius: '))
f = (c * 9/5) + 32
print("The value of input celsius in Fahrenhiet is : ", f)
print('\n')

# Kilometer to Meter
km = float(input('Enter distance in Kilometers: '))
meter = km * 1000
print('The value input distance in Meters is :', meter)