#Program to demonstrate for and while loops
# For loop
print('For loop:')
names = ["Ankur Gupta", "Rohit Sharma", "Suresh Raina", "Virat Kohli", "MS Dhoni"]
for name in names:
    print('Name :', name)
print('\n')
# While loop
print('While loop:')
j = 1
while j <= 5:
    print(j)
    j += 1
