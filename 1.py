# Arithmetic Operators
a = 10
b = 3
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Exponent:", a ** b)
print("Floor Division:", a // b)

# Comparison Operators
print("Equal:", a == b)
print("Not Equal:", a != b)
print("Greater:", a > b)
print("Lesser:", a < b)
print("Greater or Equal:", a >= b)
print("Lesser or Equal:", a <= b)

# Logical Operators
x = True
y = False
print("Logical AND:", x and y)
print("Logical OR:", x or y)
print("Logical NOT:", not x)

# Assignment Operators
c = 5
c += 2
print("c after +=2:", c)
c -= 3
print("c after -=3:", c)
c *= 4
print("c after *=4:", c)
c /= 2
print("c after /=2:", c)
c %= 3
print("c after %=3:", c)

# Bitwise Operators
print("Bitwise AND:", a & b)
print("Bitwise OR:", a | b)
print("Bitwise XOR:", a ^ b)
print("Bitwise NOT:", ~a)
print("Bitwise Left Shift:", a << 2)
print("Bitwise Right Shift:", a >> 2)

# Identity Operators
print("Identity 'is':", a is b)
print("Identity 'is not':", a is not b)

# Membership Operators
list_1 = [1, 2, 3]
print("Membership 'in':", 2 in list_1)
print("Membership 'not in':", 4 not in list_1)
